import type { Iso3, ProductId } from '../api/types';

/**
 * Scenario keyframes for mock data.
 *
 * - `world`: world total in the product's unit at given years (linear in between).
 * - `shares`: country share of world production at given years.
 *   Before a country's first keyframe it produces 0 (lets us model new entrants);
 *   after the last keyframe the last share is held.
 * - `gaps`: years with no reported data (rendered as "no data", not as zero).
 *
 * Numbers are plausible orders of magnitude, NOT real statistics.
 * Four products carry deliberate demo stories (see README):
 *   cobalt mined vs refined, nickel (Indonesia), lithium (Australia vs Chile), graphite.
 */
export type Keyframe = readonly [year: number, value: number];

export interface CountrySeries {
  shares: Keyframe[];
  gaps?: number[];
}

export interface ProductScenario {
  world: Keyframe[];
  shares: Partial<Record<Iso3, CountrySeries>>;
}

const s = (...shares: Keyframe[]): CountrySeries => ({ shares });

